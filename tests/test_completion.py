def test_path_option_has_path_type():
    """Path options use click.Path so Click's built-in file/dir completion applies."""
    export = cli.commands["export"]
    out_opt = next(p for p in export.params if "--out" in p.opts or "-o" in p.opts)
    assert out_opt.type.name == "path"


def test_completers_soft_fail_on_broken_cfg():
    bad = {"config_dir": "/nonexistent/wt-config-xyz", "org_files": ["/nope"],
           "data_dir": "/nope", "specs_dir": "/nope", "outbox_dir": "/nope",
           "org_todo_keywords": ["TODO", "|", "DONE"],
           "org_idea_keywords": ["IDEA", "|", "PROMOTED"]}
    ctx = _ctx(bad)
    assert C.complete_project(ctx, None, "") == []
    assert C.complete_idea_id(ctx, None, "") == []
    assert C.complete_spec_id(ctx, None, "") == []
    assert C.complete_outbound_id(ctx, None, "") == []
    assert C.complete_mapped_topic(ctx, None, "") == []
    assert C.complete_task_selector(ctx, None, "") == []


